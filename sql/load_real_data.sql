
-- 0) empty the schema tables (also removes the 3-character test data) and restart the surrogate keys
TRUNCATE fact_trait_similarity, fact_job_trait_importance, fact_character_trait_score,
         dim_character, dim_job, dim_onet_trait, dim_character_trait RESTART IDENTITY CASCADE;

-- 1) staging tables (raw copies of the clean CSVs)
DROP TABLE IF EXISTS stg_characters;
CREATE TABLE stg_characters (character_code TEXT, name TEXT, work_code TEXT, work_name TEXT);
DROP TABLE IF EXISTS stg_traits;
CREATE TABLE stg_traits (trait_id INTEGER, trait_low TEXT, trait_high TEXT);
DROP TABLE IF EXISTS stg_scores;
CREATE TABLE stg_scores (character_code TEXT, trait_id INTEGER, score NUMERIC);
DROP TABLE IF EXISTS stg_jobs;
CREATE TABLE stg_jobs (onet_code TEXT, title TEXT);
DROP TABLE IF EXISTS stg_onet_traits;
CREATE TABLE stg_onet_traits (name TEXT);
DROP TABLE IF EXISTS stg_importance;
CREATE TABLE stg_importance (onet_code TEXT, trait_name TEXT, importance NUMERIC);

\copy stg_characters FROM '/clean/characters.csv' CSV HEADER
\copy stg_traits FROM '/clean/traits.csv' CSV HEADER
\copy stg_scores FROM '/clean/scores_long.csv' CSV HEADER
\copy stg_jobs FROM '/clean/jobs.csv' CSV HEADER
\copy stg_onet_traits FROM '/clean/onet_traits.csv' CSV HEADER
\copy stg_importance FROM '/clean/importance.csv' CSV HEADER

-- 2) dimensions (the surrogate keys are generated by the database)
INSERT INTO dim_character (character_code, name, work_code, work_name)
SELECT character_code, name, work_code, work_name FROM stg_characters ORDER BY character_code;

INSERT INTO dim_character_trait (trait_id, trait_low, trait_high)
SELECT trait_id, trait_low, trait_high FROM stg_traits ORDER BY trait_id;

INSERT INTO dim_job (title, onet_code)
SELECT title, onet_code FROM stg_jobs ORDER BY onet_code;

INSERT INTO dim_onet_trait (name)
SELECT name FROM stg_onet_traits;

-- 3) facts: swap the natural keys (codes, names) for the surrogate keys
INSERT INTO fact_character_trait_score (character_key, char_trait_key, score)
SELECT c.character_key, t.char_trait_key, s.score
FROM stg_scores s
JOIN dim_character c       ON c.character_code = s.character_code
JOIN dim_character_trait t ON t.trait_id = s.trait_id;

INSERT INTO fact_job_trait_importance (job_key, onet_trait_key, importance)
SELECT j.job_key, o.onet_trait_key, i.importance
FROM stg_importance i
JOIN dim_job j        ON j.onet_code = i.onet_code
JOIN dim_onet_trait o ON o.name = i.trait_name;

-- 4) row counts to check against the expected numbers
SELECT 'dim_character' AS tbl, COUNT(*) AS n_rows, 2125 AS expected FROM dim_character
UNION ALL SELECT 'dim_character_trait', COUNT(*), 525 FROM dim_character_trait
UNION ALL SELECT 'dim_job', COUNT(*), 891 FROM dim_job
UNION ALL SELECT 'dim_onet_trait', COUNT(*), 21 FROM dim_onet_trait
UNION ALL SELECT 'fact_character_trait_score', COUNT(*), 1115625 FROM fact_character_trait_score
UNION ALL SELECT 'fact_job_trait_importance', COUNT(*), 18711 FROM fact_job_trait_importance;
